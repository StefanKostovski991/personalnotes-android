#!/usr/bin/env python3
"""Regenerate design/logo-preview.svg from the Android vector drawable.

The app mark lives in app/src/main/res/drawable/ic_launcher_foreground.xml. Keeping a second,
hand-maintained copy for design review invites the two drifting apart, so the preview is derived
from the drawable instead.

Usage:
    python3 design/sync-logo-preview.py

The preview is a plain SVG: open it in any browser, or rasterise it with
    qlmanage -t -s 512 -o . design/logo-preview.svg
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VECTOR = REPO / "app/src/main/res/drawable/ic_launcher_foreground.xml"
PREVIEW = REPO / "design/logo-preview.svg"

# Kept in sync with NotesPalette / ic_launcher_background.xml.
BACKGROUND_STOPS = [
    ("0", "#FFE9A3"),
    ("0.55", "#FFC93C"),
    ("1", "#FFA000"),
]


def read_layers() -> list[tuple[str, str]]:
    """Returns (fillColor, pathData) pairs in draw order."""
    xml = VECTOR.read_text(encoding="utf-8")
    fills = re.findall(r'android:fillColor="([^"]+)"', xml)
    paths = re.findall(r'android:pathData="([^"]+)"', xml)
    if len(fills) != len(paths):
        sys.exit(
            f"{VECTOR.relative_to(REPO)}: found {len(fills)} fills but {len(paths)} paths; "
            "refusing to generate a mismatched preview.",
        )
    return list(zip(fills, paths))


def main() -> None:
    layers = read_layers()
    stops = "\n".join(
        f'      <stop offset="{offset}" stop-color="{colour}"/>'
        for offset, colour in BACKGROUND_STOPS
    )
    paths = "\n".join(
        f'  <path d="{d}" fill="{fill}"/>' for fill, d in layers
    )

    PREVIEW.write_text(
        f"""<svg xmlns="http://www.w3.org/2000/svg" width="432" height="432" viewBox="0 0 108 108">
  <!-- Generated by design/sync-logo-preview.py - edit the vector drawable, not this file. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse">
{stops}
    </linearGradient>
  </defs>

  <rect x="0" y="0" width="108" height="108" fill="url(#bg)"/>

{paths}
</svg>
""",
        encoding="utf-8",
    )
    print(f"wrote {PREVIEW.relative_to(REPO)} ({len(layers)} layers)")


if __name__ == "__main__":
    main()
